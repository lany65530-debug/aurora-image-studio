const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5175/novel-preview.html')
    await page.locator('[data-act="outline"]').click()
    await page.locator('.novel-outline').waitFor()
    for (const tab of ['characters', 'locations', 'foreshadowing', 'summaries']) {
      await page.locator('[data-tab="' + tab + '"]').click()
      assert.equal(await page.locator('.novel-ol-tabs .on').getAttribute('data-tab'), tab)
    }
    await page.locator('[data-tab="characters"]').click()
    await page.locator('#nc-open').click()
    await page.locator('#nc-name').fill('林夏')
    await page.locator('#nc-role').fill('主角')
    await page.locator('#nc-desc').fill('收到来信后踏上归途')
    await page.locator('#nc-add').click()
    await page.locator('[data-tab="locations"]').click()
    await page.locator('#nl-open').click()
    await page.locator('#nl-name').fill('渡口')
    await page.locator('#nl-desc').fill('故事开始的地方')
    await page.locator('#nl-add').click()
    await page.locator('[data-tab="foreshadowing"]').click()
    await page.locator('#fs-input').fill('没有署名的信')
    await page.locator('#fs-add').click()
    await page.locator('#ol-save').click()
    await page.locator('[data-act="outline"]').click()
    await page.locator('[data-tab="characters"]').click()
    assert.match(await page.locator('.novel-ol-body').innerText(), /林夏/)
    await page.locator('[data-tab="locations"]').click()
    assert.match(await page.locator('.novel-ol-body').innerText(), /渡口/)
    await page.locator('[data-tab="foreshadowing"]').click()
    assert.match(await page.locator('.novel-ol-body').innerText(), /没有署名的信/)
    await page.screenshot({ path: 'novel-outline-fixed.png' })
    await page.locator('.novel-outline [data-x]').click()
    await page.evaluate(() => {
      window.previewWorkspace.novels[0].outline = { foreshadowing: ['旧版伏笔'] }
    })
    await page.locator('[data-act="outline"]').click()
    await page.locator('[data-tab="foreshadowing"]').click()
    assert.match(await page.locator('.novel-ol-body').innerText(), /旧版伏笔/)
    await page.locator('#fs-input').fill('取消时不应保存')
    await page.locator('#fs-add').click()
    await page.locator('.novel-outline [data-x]').click()
    assert.deepEqual(await page.evaluate(() => window.previewWorkspace.novels[0].outline), { foreshadowing: ['旧版伏笔'] })
    await page.evaluate(() => { delete window.previewWorkspace.novels[0].outline })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('[data-act="outline"]').click()
    await page.locator('.novel-outline').waitFor()
    const bounds = await page.locator('.novel-ol-card').boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
    assert.deepEqual(errors, [])
    console.log('PASS: missing fields, all outline tabs, add/save/reopen, legacy foreshadowing, cancel isolation, empty outline, mobile.')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
